def e(n, k):
    i = 1            # 2
    while i < n:     # 3 * (m + 1)
        j = 1        # 2 * m
        while j < n: # 3 * m * (m + 1)
            k += 1   # 4 * m^2
            j *= 2   # 4 * m^2
        i *= 2       # 4 * m
# ​n = 2^m -> m = log2(n)
