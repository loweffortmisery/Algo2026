'''2.10. Визначте асимптотичну оцінку виконання функції у найгіршому випадку
в термінах 𝑂–«великого» для функції:'''
def f(n):
    sum = 0
    for i in range(1, n + 1): #n*O(1)
        sum = sum + i #n*O(1)
    return sum
# O(n)

